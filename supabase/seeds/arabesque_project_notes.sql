insert into public.project_notes(
  project_id, section_id, title, position, source_reference, metadata
)
select
  project_sections.project_id,
  project_sections.id,
  note_seed.title,
  note_seed.position,
  note_seed.source_reference,
  jsonb_build_object(
    'seed', 'arabesque-initial-notes',
    'source', 'user-provided-live-project-notes'
  )
from note_seed
join project_sections on project_sections.title = note_seed.section_title
where not exists (
  select 1
  from public.project_notes existing
  where existing.project_id = project_sections.project_id
    and existing.section_id = project_sections.id
    and existing.title = note_seed.title
);
