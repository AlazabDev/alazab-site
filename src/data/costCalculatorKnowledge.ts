// Smart insights - يولد ملخص ذكي بناءً على المدخلات
export function generateSmartInsights(input: {
  category: string | null;
  subtype: string | null;
  area: number;
  finishLevel: string | null;
  enabledItemsCount: number;
  totalItemsCount: number;
  total: number;
  perMeter: number;
}): string[] {
  const insights: string[] = [];
  const { category, subtype, area, enabledItemsCount, totalItemsCount, perMeter } = input;

  if (area > 0 && area < 50) insights.push("⚠️ المساحة صغيرة نسبيًا — تأكد من إدراج جميع البنود الأساسية لتجنب نقص في التقدير.");
  if (area >= 200) insights.push("✅ مشروع كبير — ننصح بمعاينة مجانية للحصول على عرض دقيق وخصومات الكميات.");
  if (enabledItemsCount < totalItemsCount * 0.3) insights.push("💡 فعّلت بنود قليلة. كل بند تفعّله يزيد دقة التقدير ويقلل المفاجآت.");
  if (enabledItemsCount >= totalItemsCount * 0.8) insights.push("🎯 تقديرك دقيق جدًا لأنك حدّدت معظم البنود.");
  if (category === "commercial" && (subtype === "restaurant" || subtype === "cafe")) {
    insights.push("🍽️ مشاريع المطاعم والكافيهات تحتاج تراخيص خاصة — فريقنا يساعدك في التراخيص.");
  }
  if (category === "commercial" && subtype === "chain_branch") {
    insights.push("🏷️ فرع سلسلة — لدينا خبرة في تكرار التشطيب بين الفروع بنفس الجودة.");
  }
  if (perMeter > 12000) insights.push("💎 سعر المتر يضعك في الفئة الفاخرة — نوفر خامات مستوردة وتنفيذ متخصص.");
  insights.push("📋 التقدير أولي ويحتاج معاينة موقعية لاعتماد العرض النهائي. المعاينة مجانية داخل القاهرة الكبرى.");
  return insights;
}

